"""Two non-polynomial benchmark families for the dictionary construction.

``kuramoto3(b)``
    Three coupled phase oscillators on the torus,
    ``theta_i' = omega_i + (1/3) sum_j sin(theta_j - theta_i) - b delta_{i1} sin(theta_1)``.
    At ``b = 0`` the global phase shift ``d/dtheta_1 + d/dtheta_2 + d/dtheta_3``
    is an exact symmetry; the pinning term ``b sin(theta_1)`` breaks it, and
    the defect of the phase shift grows continuously with ``b``.  Dictionary:
    the constant, the first harmonics of each angle and the products of first
    harmonics of two different angles (19 functions), the standard Fourier
    library for phase oscillators.  Candidate generators: the three constant
    fields and the 18 first-harmonic fields ``cos/sin(theta_j) d/dtheta_i``.
    Target measure: uniform on the torus; a 6-point grid per angle integrates
    every integrand exactly.

``radial_flow(eps)``
    The planar flow ``r' = r(1 - r)``, ``phi' = 1 / (1 + r^2)`` (exactly
    rotation invariant and not polynomial in Cartesian coordinates), plus
    ``eps x^2 d/dx``.  Dictionary: polynomials of degree at most two and the
    four functions ``x r, y r, x/(1+r^2), y/(1+r^2)`` (10 functions), so the
    class contains the truth for every ``eps``.  Candidate generators: affine.
    Target measure: uniform on the unit disc, integrated in polar coordinates.

``pendulum(c)``
    The damped pendulum ``theta' = omega``, ``omega' = -sin(theta) - c omega``
    on the box ``[-1.5, 1.5]^2``, with the library
    ``{1, theta, omega, theta^2, theta omega, omega^2, sin theta, cos theta}``
    (a standard SINDy library for this system), so the class contains the
    truth.  No affine generator is a symmetry.  Gauss--Legendre in both
    coordinates; the trigonometric integrands are not polynomial, and the rule
    size is chosen so that its error is at rounding level.

The Kuramoto family is kept for a different purpose: its symmetry is
generated by a constant field, for which ``D xi = 0`` and the relative defect
degenerates (it equals one unless the bracket vanishes, where it is 0/0).
"""

from __future__ import annotations

from fractions import Fraction
from itertools import combinations

import numpy as np

from .dictionary import (Dictionary, DictionaryProblem, Generator, disc_rule,
                         product_rule, torus_rule)

__all__ = ["kuramoto_problem", "kuramoto_beta", "radial_problem", "radial_beta",
           "pendulum_problem", "pendulum_beta", "KURAMOTO_OMEGA"]

KURAMOTO_OMEGA = (Fraction(1), Fraction(1, 2), Fraction(-1, 3))


# ---------------------------------------------------------------- Kuramoto
def _trig(i, kind):
    if kind == "c":
        return (lambda X, i=i: np.cos(X[:, i]),
                lambda X, i=i: _grad1(X, i, -np.sin(X[:, i])))
    return (lambda X, i=i: np.sin(X[:, i]),
            lambda X, i=i: _grad1(X, i, np.cos(X[:, i])))


def _grad1(X, i, v):
    G = np.zeros_like(X)
    G[:, i] = v
    return G


def _kuramoto_dictionary(n=3) -> Dictionary:
    funcs, grads, names = [lambda X: np.ones(X.shape[0])], [lambda X: np.zeros_like(X)], ["1"]
    for i in range(n):
        for kind in "cs":
            f, g = _trig(i, kind)
            funcs.append(f); grads.append(g); names.append(f"{kind}{i}")
    for i, j in combinations(range(n), 2):
        for ki in "cs":
            for kj in "cs":
                fi, gi = _trig(i, ki)
                fj, gj = _trig(j, kj)
                funcs.append(lambda X, fi=fi, fj=fj: fi(X) * fj(X))
                grads.append(lambda X, fi=fi, fj=fj, gi=gi, gj=gj:
                             gi(X) * fj(X)[:, None] + gj(X) * fi(X)[:, None])
                names.append(f"{ki}{i}{kj}{j}")
    return Dictionary(funcs, grads, names)


def _kuramoto_generators(n=3):
    gens = []
    for i in range(n):
        gens.append(Generator(lambda X, i=i: _grad1(X, i, np.ones(X.shape[0])),
                              lambda X: np.zeros((X.shape[0], X.shape[1], X.shape[1])),
                              f"d/dth{i}"))
    for i in range(n):
        for j in range(n):
            for kind in "cs":
                f, g = _trig(j, kind)

                def field(X, i=i, f=f):
                    return _grad1(X, i, f(X))

                def jac(X, i=i, g=g):
                    J = np.zeros((X.shape[0], X.shape[1], X.shape[1]))
                    J[:, i, :] = g(X)
                    return J
                gens.append(Generator(field, jac, f"{kind}{j}*d/dth{i}"))
    return gens


def kuramoto_problem(M: int = 6) -> DictionaryProblem:
    rule = torus_rule(M)
    X, W = product_rule(rule, rule, rule)
    return DictionaryProblem.build(3, _kuramoto_dictionary(), _kuramoto_generators(),
                                   X, W, measure_name="torus")


def kuramoto_beta(prob: DictionaryProblem, b: float) -> np.ndarray:
    """Coefficients of the three-oscillator system with pinning ``b``."""
    terms = {}
    for i, om in enumerate(KURAMOTO_OMEGA):
        terms[(i, "1")] = float(om)
    # (1/3) sin(theta_j - theta_i) = (1/3)(s_j c_i - c_j s_i)
    for i in range(3):
        for j in range(3):
            if i == j:
                continue
            a, c = min(i, j), max(i, j)
            # product names are ordered by the smaller angle index first
            sj_ci = f"c{a}s{c}" if i == a else f"s{a}c{c}"
            cj_si = f"s{a}c{c}" if i == a else f"c{a}s{c}"
            terms[(i, sj_ci)] = terms.get((i, sj_ci), 0.0) + 1.0 / 3.0
            terms[(i, cj_si)] = terms.get((i, cj_si), 0.0) - 1.0 / 3.0
    terms[(0, "s0")] = terms.get((0, "s0"), 0.0) - b
    return prob.beta_from_terms(terms)


def kuramoto_sample(rng, N: int) -> np.ndarray:
    return rng.uniform(0.0, 2 * np.pi, size=(N, 3))


# ---------------------------------------------------------- radial flow
def _radial_dictionary() -> Dictionary:
    def r(X):
        return np.sqrt(np.sum(X ** 2, axis=1))

    def mono(px, py):
        f = lambda X: X[:, 0] ** px * X[:, 1] ** py
        def g(X):
            G = np.zeros_like(X)
            if px:
                G[:, 0] = px * X[:, 0] ** (px - 1) * X[:, 1] ** py
            if py:
                G[:, 1] = py * X[:, 0] ** px * X[:, 1] ** (py - 1)
            return G
        return f, g, f"x^{px}y^{py}"

    funcs, grads, names = [], [], []
    for px, py in [(0, 0), (1, 0), (0, 1), (2, 0), (1, 1), (0, 2)]:
        f, g, nm = mono(px, py)
        funcs.append(f); grads.append(g); names.append(nm)
    for k, nm in [(0, "x r"), (1, "y r")]:
        funcs.append(lambda X, k=k: X[:, k] * r(X))

        def g(X, k=k):
            rr = np.maximum(r(X), 1e-300)
            G = (X[:, k] / rr)[:, None] * X
            G[:, k] += rr
            return G
        grads.append(g); names.append(nm)
    for k, nm in [(0, "x/(1+r2)"), (1, "y/(1+r2)")]:
        funcs.append(lambda X, k=k: X[:, k] / (1.0 + np.sum(X ** 2, axis=1)))

        def g(X, k=k):
            s = 1.0 + np.sum(X ** 2, axis=1)
            G = (-2.0 * X[:, k] / s ** 2)[:, None] * X
            G[:, k] += 1.0 / s
            return G
        grads.append(g); names.append(nm)
    return Dictionary(funcs, grads, names)


def _affine_generators(n=2):
    gens = []
    for i in range(n):
        for j in range(n):
            def field(X, i=i, j=j):
                return _grad1(X, i, X[:, j])

            def jac(X, i=i, j=j):
                J = np.zeros((X.shape[0], n, n))
                J[:, i, j] = 1.0
                return J
            gens.append(Generator(field, jac, f"x{j}*d/dx{i}"))
    for i in range(n):
        gens.append(Generator(lambda X, i=i: _grad1(X, i, np.ones(X.shape[0])),
                              lambda X: np.zeros((X.shape[0], n, n)), f"d/dx{i}"))
    return gens


def radial_problem(Mr: int = 40, Mphi: int = 24) -> DictionaryProblem:
    X, W = disc_rule(Mr, Mphi, 0.0, 1.0)
    return DictionaryProblem.build(2, _radial_dictionary(), _affine_generators(),
                                   X, W, measure_name="disc")


def radial_beta(prob: DictionaryProblem, eps: float) -> np.ndarray:
    terms = {(0, "x^1y^0"): 1.0, (0, "x r"): -1.0, (0, "y/(1+r2)"): -1.0,
             (1, "x^0y^1"): 1.0, (1, "y r"): -1.0, (1, "x/(1+r2)"): 1.0}
    if eps:
        terms[(0, "x^2y^0")] = float(eps)
    return prob.beta_from_terms(terms)


def disc_sample(rng, N: int) -> np.ndarray:
    r = np.sqrt(rng.uniform(size=N))
    phi = rng.uniform(0, 2 * np.pi, size=N)
    return np.stack([r * np.cos(phi), r * np.sin(phi)], axis=1)


# ---------------------------------------------------------- pendulum
def _pendulum_dictionary() -> Dictionary:
    funcs, grads, names = [], [], []

    def mono(pt, pw):
        f = lambda X: X[:, 0] ** pt * X[:, 1] ** pw
        def g(X):
            G = np.zeros_like(X)
            if pt:
                G[:, 0] = pt * X[:, 0] ** (pt - 1) * X[:, 1] ** pw
            if pw:
                G[:, 1] = pw * X[:, 0] ** pt * X[:, 1] ** (pw - 1)
            return G
        return f, g, f"th^{pt}om^{pw}"

    for pt, pw in [(0, 0), (1, 0), (0, 1), (2, 0), (1, 1), (0, 2)]:
        f, g, nm = mono(pt, pw)
        funcs.append(f); grads.append(g); names.append(nm)
    funcs.append(lambda X: np.sin(X[:, 0]))
    grads.append(lambda X: _grad1(X, 0, np.cos(X[:, 0]))); names.append("sin th")
    funcs.append(lambda X: np.cos(X[:, 0]))
    grads.append(lambda X: _grad1(X, 0, -np.sin(X[:, 0]))); names.append("cos th")
    return Dictionary(funcs, grads, names)


PENDULUM_SCALE = 1.5


def pendulum_problem(M: int = 32) -> DictionaryProblem:
    from .dictionary import gauss_legendre_rule
    rule = gauss_legendre_rule(M, -PENDULUM_SCALE, PENDULUM_SCALE)
    X, W = product_rule(rule, rule)
    return DictionaryProblem.build(2, _pendulum_dictionary(), _affine_generators(),
                                   X, W, measure_name="box")


def pendulum_beta(prob: DictionaryProblem, c: float = 0.1) -> np.ndarray:
    return prob.beta_from_terms({(0, "th^0om^1"): 1.0, (1, "sin th"): -1.0,
                                 (1, "th^0om^1"): -float(c)})


def box_sample(rng, N: int, scale: float = PENDULUM_SCALE) -> np.ndarray:
    return rng.uniform(-scale, scale, size=(N, 2))
